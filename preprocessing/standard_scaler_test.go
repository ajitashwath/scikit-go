func TestStandardScaler_SaveLoadRoundTrip(t *testing.T) {
	scaler := NewStandardScaler()
	X := [][]float64{{1.0, 2.0}, {2.0, 3.0}, {3.0, 4.0}, {4.0, 5.0}, {5.0, 6.0}}
	if err := scaler.Fit(X); err != nil {
		t.Fatalf("Fit failed: %v", err)
	}

	tmpFile := filepath.Join(t.TempDir(), "scaler.bin")
	if err := scaler.Save(tmpFile); err != nil {
		t.Fatalf("Save failed: %v", err)
	}

	loaded, err := LoadStandardScaler(tmpFile)
	if err != nil {
		t.Fatalf("LoadStandardScaler failed: %v", err)
	}

	assertSliceClose(t, "loaded.Mean", loaded.Mean, scaler.Mean)
	assertSliceClose(t, "loaded.Scale", loaded.Scale, scaler.Scale)
	assertSliceClose(t, "loaded.Var", loaded.Var, scaler.Var)

	orig, _ := scaler.Transform(X)
	loadedScaled, err := loaded.Transform(X)
	if err != nil {
		t.Fatalf("loaded scaler Transform failed: %v", err)
	}
	assertMatrixClose(t, "loaded transform", loadedScaled, orig)
}

